#!/usr/bin/env python3
"""Package finalized RGBA frames as a deterministic Pixelorama v1.2 project."""

from __future__ import annotations

import argparse
import json
import zipfile
from pathlib import Path

from PIL import Image


PXO_MIMETYPE = b"application/x-pixelorama"
ZIP_TIMESTAMP = (1980, 1, 1, 0, 0, 0)


def _zip_info(name: str) -> zipfile.ZipInfo:
    info = zipfile.ZipInfo(name, ZIP_TIMESTAMP)
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o644 << 16
    return info


def _write(archive: zipfile.ZipFile, name: str, data: bytes) -> None:
    archive.writestr(_zip_info(name), data)


def _color_string(hex_color: str) -> str:
    value = hex_color.strip().lstrip("#")
    if len(value) != 6:
        raise ValueError(f"expected #RRGGBB palette color, got {hex_color!r}")
    channels = [int(value[index : index + 2], 16) / 255 for index in (0, 2, 4)]
    return "(" + ", ".join(f"{channel:.8f}" for channel in channels) + ", 1.0)"


def _palette_payload(name: str, colors: list[str]) -> list[dict[str, str]]:
    if not colors:
        return []
    payload = {
        "comment": "The Horde prototype palette",
        "colors": [
            {"color": _color_string(color), "index": index}
            for index, color in enumerate(colors)
        ],
        "width": 8,
        "height": max(1, (len(colors) + 7) // 8),
    }
    return [{name: json.dumps(payload, indent=1, sort_keys=True)}]


def _read_palette(path: Path | None) -> list[str]:
    if path is None:
        return []
    if path.suffix.lower() == ".png":
        colors = list(dict.fromkeys(Image.open(path).convert("RGB").getdata()))
        return ["#" + "".join(f"{channel:02X}" for channel in color) for color in colors]
    colors: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        for token in line.replace("`", " ").replace(",", " ").split():
            if len(token) == 7 and token.startswith("#"):
                try:
                    int(token[1:], 16)
                except ValueError:
                    continue
                colors.append(token.upper())
    return list(dict.fromkeys(colors))


def package_project(
    output: Path,
    frame_paths: list[Path],
    *,
    tag: str,
    frame_ms: int,
    palette_path: Path | None = None,
) -> None:
    if not frame_paths:
        raise ValueError("at least one frame is required")
    if frame_ms <= 0:
        raise ValueError("frame duration must be positive")

    frames = [Image.open(path).convert("RGBA") for path in frame_paths]
    size = frames[0].size
    if any(frame.size != size for frame in frames):
        raise ValueError("all frames must have identical dimensions")

    palette_name = "The Horde Prototype"
    palette = _read_palette(palette_path)
    fps = 1000.0 / frame_ms
    data = {
        "pixelorama_version": "v1.2.1-stable",
        "pxo_version": 7,
        "size_x": size[0],
        "size_y": size[1],
        "color_mode": 5,
        "tile_mode_x_basis_x": 0,
        "tile_mode_x_basis_y": 0,
        "tile_mode_y_basis_x": 0,
        "tile_mode_y_basis_y": 0,
        "layers": [
            {
                "animated_params": 'Dictionary[String, Dictionary]({\n"opacity": {}\n})',
                "blend_mode": 0,
                "clipping_mask": False,
                "effects": [],
                "locked": False,
                "metadata": {},
                "name": "Ember",
                "new_cels_linked": False,
                "opacity": 1.0,
                "parent": -1,
                "type": 0,
                "ui_color": "(0.0, 0.0, 0.0, 0.0)",
                "visible": True,
            }
        ],
        "tags": [{"name": tag, "color": "f2760d", "from": 1, "to": len(frames)}],
        "guides": [],
        "symmetry_points": [float(size[0] - 1), float(size[1] - 1)],
        "frames": [
            {
                "cels": [
                    {
                        "metadata": {},
                        "opacity": 1.0,
                        "ui_color": "(0.0, 0.0, 0.0, 0.0)",
                        "z_index": 0,
                    }
                ],
                "duration": 1.0,
                "metadata": {},
            }
            for _ in frames
        ],
        "current_frame": 0,
        "current_layer": 0,
        "brushes": [],
        "palettes": _palette_payload(palette_name, palette),
        "project_current_palette_name": palette_name if palette else "",
        "reference_images": [],
        "tilesets": [],
        "vanishing_points": [],
        "fps": fps,
        "license": "Proprietary",
        "user_data": "Generated by The Horde prototype sprite pipeline",
        "author_display_name": "The Horde team",
        "author_real_name": "",
        "author_contact": "",
        "author_company": "",
        "metadata": {
            "pipeline": "horde-sprite-prototype",
            "frame_duration_ms": frame_ms,
            "source_frames": [path.name for path in frame_paths],
        },
        "export_profile": None,
    }

    output.parent.mkdir(parents=True, exist_ok=True)
    preview = frames[0].copy()
    preview.thumbnail((256, 256), Image.Resampling.NEAREST)
    from io import BytesIO

    preview_bytes = BytesIO()
    preview.save(preview_bytes, format="PNG")

    with zipfile.ZipFile(output, "w") as archive:
        _write(archive, "data.json", json.dumps(data, separators=(",", ":"), sort_keys=True).encode())
        _write(archive, "mimetype", PXO_MIMETYPE)
        _write(archive, "preview.png", preview_bytes.getvalue())
        for index, frame in enumerate(frames, start=1):
            _write(archive, f"image_data/frames/{index}/layer_1", frame.tobytes())
            _write(archive, f"image_data/frames/{index}/indices_layer_1", b"\x00")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--tag", required=True)
    parser.add_argument("--frame-ms", type=int, required=True)
    parser.add_argument("--palette", type=Path)
    parser.add_argument("frames", nargs="+", type=Path)
    args = parser.parse_args()
    package_project(
        args.output,
        args.frames,
        tag=args.tag,
        frame_ms=args.frame_ms,
        palette_path=args.palette,
    )


if __name__ == "__main__":
    main()
